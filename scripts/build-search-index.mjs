/**
 * Generates src/shared/searchIndex.generated.ts — the cross-course lesson index.
 *
 * Why generated rather than imported: a curriculum registry references every
 * Theory component and every lab, so importing one to read its titles drags a
 * whole course's simulations into the search route's bundle. Two courses would
 * roughly double it. Scraping the titles at build time gives the search page a
 * few kB of plain strings instead.
 *
 * Runs from `predev` and `prebuild`, so the index cannot silently go stale.
 * It fails loudly rather than emitting an empty index, because a search box
 * that quietly finds nothing is worse than a broken build.
 */

import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const SRC = path.join(ROOT, "src");
const OUT = path.join(SRC, "shared", "searchIndex.generated.ts");

/** Courses to index — must match the ids in shared/courses.ts. */
const COURSES = readdirSync(SRC, { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(path.join(SRC, d.name, "lib/curriculum/registry.ts")))
  .map((d) => d.name);

/** Strip JSX-ish noise from a scraped string literal. */
const clean = (s) =>
  s
    .replace(/\\"/g, '"')
    .replace(/\\n/g, " ")
    .replace(/\s+/g, " ")
    .trim();

/** Pull `key: "value"` allowing the value to sit on the following line. */
function field(block, key) {
  const m = block.match(new RegExp(`\\b${key}:\\s*\\n?\\s*"((?:[^"\\\\]|\\\\.)*)"`));
  return m ? clean(m[1]) : "";
}

function indexCourse(course) {
  const dir = path.join(SRC, course, "lib/curriculum");
  const unitFiles = readdirSync(dir).filter((f) => /^unit\d+\.tsx$/.test(f));
  // numeric order, so 10 does not sort before 2
  unitFiles.sort((a, b) => Number(a.match(/\d+/)[0]) - Number(b.match(/\d+/)[0]));

  const rows = [];
  for (const file of unitFiles) {
    const src = readFileSync(path.join(dir, file), "utf8");
    const unitBlock = src.slice(0, src.indexOf("lessons:"));
    const unitNum = Number(field(unitBlock, "num") || (unitBlock.match(/num:\s*(\d+)/) ?? [])[1] || 0);
    const unitTitle = field(unitBlock, "title");

    // split on lesson boundaries: every lesson object starts with a slug
    const parts = src.split(/\n\s{4,6}slug:\s*"/).slice(1);
    parts.forEach((part, i) => {
      const slug = part.slice(0, part.indexOf('"'));
      const head = part.slice(0, 4000); // title/subtitle live near the top
      rows.push({
        course,
        slug,
        unitNum,
        unitTitle,
        lessonNo: `${unitNum}.${i + 1}`,
        title: field(head, "title"),
        subtitle: field(head, "subtitle"),
      });
    });
  }

  // German titles, if the course ships them
  const metaPath = path.join(dir, "de", "meta.ts");
  if (existsSync(metaPath)) {
    const meta = readFileSync(metaPath, "utf8");
    const lessonMeta = meta.slice(meta.indexOf("lessonMetaDe"));
    for (const row of rows) {
      const key = new RegExp(`\\n  "?${row.slug}"?:\\s*\\{([\\s\\S]*?)\\n  \\},`);
      const m = lessonMeta.match(key);
      if (m) {
        row.titleDe = field(m[1], "title");
        row.subtitleDe = field(m[1], "subtitle");
      }
    }
  }
  return rows;
}

const all = COURSES.flatMap(indexCourse);

const missingTitles = all.filter((r) => !r.title);
if (all.length === 0) {
  console.error("[search-index] scraped 0 lessons — the curriculum format has changed");
  process.exit(1);
}
if (missingTitles.length) {
  console.error(
    `[search-index] ${missingTitles.length} lesson(s) scraped without a title:`,
    missingTitles.map((r) => `${r.course}/${r.slug}`).join(", ")
  );
  process.exit(1);
}

const body = `/* GENERATED by scripts/build-search-index.mjs — do not edit by hand.
 * Regenerated automatically on \`npm run dev\` and \`npm run build\`. */

export interface SearchRow {
  course: string;
  slug: string;
  lessonNo: string;
  unitNum: number;
  unitTitle: string;
  title: string;
  subtitle: string;
  titleDe?: string;
  subtitleDe?: string;
}

export const SEARCH_INDEX: SearchRow[] = ${JSON.stringify(all, null, 2)};
`;

writeFileSync(OUT, body);
console.log(
  `[search-index] ${all.length} lessons across ${COURSES.length} course(s): ${COURSES.join(", ")}`
);
